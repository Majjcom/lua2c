std::string convert(std::string_view input, const Options& options) {
    const bool binary = options.input_kind == InputKind::Bytecode ||
        (options.input_kind == InputKind::Auto && !input.empty() && input[0] == '\x1b');
    if (binary) return emit_bytecode(input, options);
    if (input.size() >= 3 && input.substr(0, 3) == std::string_view("\xef\xbb\xbf", 3)) input.remove_prefix(3);
    std::string source;
    if (!input.empty() && input[0] == '#') {
        auto newline = input.find('\n');
        source = "\n";
        if (newline != std::string_view::npos) source.append(input.substr(newline + 1));
        input = source;
    }
    std::unique_ptr<lua_State, decltype(&lua_close)> state(luaL_newstate(), lua_close);
    if (!state) throw Error("cannot allocate Lua compiler state");
    const int status = luaL_loadbufferx(state.get(), input.empty() ? "" : input.data(),
        input.size(), options.chunk_name.c_str(), "t");
    if (status != LUA_OK) {
        const char* message = lua_tostring(state.get(), -1);
        throw Error(message ? message : "Lua compilation failed");
    }
    DumpBuffer buffer;
    const int dumpstatus = lua_dump(state.get(), writer, &buffer, 0);
    if (buffer.error) std::rethrow_exception(buffer.error);
    if (dumpstatus) throw Error("Lua bytecode serialization failed");
    return emit_bytecode(buffer.bytes, options);
}

void convert_to_file(std::string_view input, const std::filesystem::path& output,
                     const Options& options, bool generate_header) {
    const auto header = generate_header ? header_path(output) : std::filesystem::path();
    const std::string code = convert(input, options);
    const std::string declarations = generate_header ? emit_header(options) : std::string();
    write_output(output, code);
    if (generate_header) write_output(header, declarations);
}

std::string convert_file(const std::filesystem::path& input, const Options& options) {
    const auto bytes = read_input(input);
    return convert(bytes, file_options(input, options));
}
void convert_file_to_file(const std::filesystem::path& input, const std::filesystem::path& output,
                          const Options& options, bool generate_header) {
    const auto bytes = read_input(input);
    convert_to_file(bytes, output, file_options(input, options), generate_header);
}
