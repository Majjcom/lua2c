struct DumpBuffer {
    std::string bytes;
    std::exception_ptr error;
};
int writer(lua_State*, const void* bytes, std::size_t size, void* context) noexcept {
    auto& output = *static_cast<DumpBuffer*>(context);
    try { output.bytes.append(static_cast<const char*>(bytes), size); return 0; }
    catch (...) { output.error = std::current_exception(); return 1; }
}
std::string read_input(const std::filesystem::path& path) {
    std::ifstream file(path, std::ios::binary);
    if (!file) throw Error("cannot open input: " + path.u8string());
    std::string bytes((std::istreambuf_iterator<char>(file)), {});
    if (file.bad()) throw Error("cannot read input: " + path.u8string());
    return bytes;
}
Options file_options(const std::filesystem::path& path, Options options) {
    if (options.chunk_name == "=(lua2c)") options.chunk_name = "@" + path.u8string();
    return options;
}
void write_output(const std::filesystem::path& output, const std::string& contents) {
    std::ofstream file(output, std::ios::binary | std::ios::trunc);
    if (!file) throw Error("cannot open output: " + output.u8string());
    file.write(contents.data(), static_cast<std::streamsize>(contents.size()));
    file.close();
    if (!file) throw Error("cannot write output: " + output.u8string());
}
std::filesystem::path header_path(const std::filesystem::path& output) {
    auto header = output;
    header.replace_extension(".h");
    std::string extension = output.extension().u8string();
    for (auto& c : extension) if (c >= 'A' && c <= 'Z') c = static_cast<char>(c - 'A' + 'a');
    if (extension == ".h") throw Error("C output and generated header must have different paths");
    return header;
}
std::string emit_header(const Options& options) {
    const std::string guard = "LUA2C_GENERATED_" + options.module_name + "_" + options.main_name + "_H";
    return "/* Generated by lua2c. Public C/C++ entry points. */\n"
        "#ifndef " + guard + "\n#define " + guard + "\n\n"
        "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n"
        "#include \"lua.h\"\n\n"
        "/* Pass chunk arguments on the stack; returns the number of results.\n"
        "   The host initializes Lua and handles errors with lua_pcall. */\n"
        "int " + options.main_name + "(lua_State *L);\n\n"
        "/* Defined only when the generated C is built with LUA2C_API=1. */\n"
        "#if defined(LUA2C_API) && LUA2C_API\n"
        "int luaopen_" + options.module_name + "(lua_State *L);\n#endif\n\n"
        "#ifdef __cplusplus\n}\n#endif\n\n#endif /* " + guard + " */\n";
}
void strip_debug(detail::Proto& proto) {
    proto.source.reset();
    proto.lineinfo.clear();
    proto.abslineinfo.clear();
    proto.locals.clear();
    for (auto& upvalue : proto.upvalues) upvalue.name.reset();
    for (auto& child : proto.children) strip_debug(child);
    // Like luac -s, retain definition lines, instructions and upvalue descriptors.
}
std::string emit_bytecode(std::string_view input, const Options& options) {
    auto proto = detail::parse_bytecode(input); // Validate before discarding debug data.
    if (options.strip) strip_debug(proto);
    return detail::emit(std::move(proto), options.module_name, options.main_name, options.no_bytecode);
}
